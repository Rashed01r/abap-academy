import { test, expect } from "@playwright/test";
import { educationContent } from "../src/lib/education-content";
import { edit, openLesson, tab } from "./academy-helpers";
import { additionExample } from "../src/lib/curriculum";
import { ui } from "../src/lib/i18n";

for (const theme of ["light", "dark"]) test(`addition pilot: visible teaching, linked sections and retained sandbox (${theme})`, async ({page}, info) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.addInitScript(theme => {
    if (localStorage.getItem("addition-pilot-seeded")) return;
    localStorage.setItem("addition-pilot-seeded", "yes");
    localStorage.setItem("abap2-appearance", theme);
    localStorage.setItem("abap2-lesson-header:addition:objectives-seen", "seen");
    localStorage.setItem("abap2-workspace:addition:visualize", "WRITE 42.");
  }, theme);
  await page.goto("/?mission=addition");
  await openLesson(page,"addition");
  await expect(page.getByRole("tab")).toHaveText(["Learn", "Explore code", "Challenge"]);
  await expect(page.getByRole("heading", {name:"What you’ll learn"})).toBeVisible();
  await expect(page.locator(".lesson-header-objectives ul")).toBeVisible();
  const learn = page.locator("[data-addition-learn]");
  const boxes=learn.locator("[data-primary-diagram=addition] .add-box strong");
  const next=learn.getByRole("button",{name:"Run next line",exact:true});
  await expect(boxes).toHaveText(["–","–","–"]);
  await next.click();
  await expect(boxes).toHaveText(["5","–","–"]);
  await expect(learn.getByRole("definition").first()).toContainText("create a variable");
  await next.click();await next.click();
  await expect(boxes).toHaveText(["5","8","0"]);
  await next.click();
  await expect(boxes).toHaveText(["5","8","13"]);
  await expect(learn.locator('.add-code [data-state="active"]')).toContainText("lv_result = lv_first + lv_second.");
  await expect(learn.locator(".add-screen")).toContainText("Nothing on the screen yet");
  await next.click();
  await expect(learn.locator(".add-screen pre")).toHaveText("13");
  await learn.getByRole("button",{name:"Start over",exact:true}).click();
  await expect(boxes).toHaveText(["–","–","–"]);
  await learn.getByRole("button",{name:"Calculate and store"}).click();
  await expect(boxes).toHaveText(["5","8","13"]);
  await learn.getByLabel("First number").fill("-12");
  await expect(boxes).toHaveText(["-12","8","-4"]);
  await expect(learn.locator(".add-code")).toContainText("VALUE -12.");
  await learn.getByLabel("First number").fill("1.5");
  await expect(learn.getByRole("alert")).toContainText("Enter whole numbers only");
  await expect(boxes).toHaveText(["-12","8","-4"]);
  await learn.getByRole("button",{name:"It does not exist yet"}).click();
  await expect(learn.locator(".quiz").first()).toContainText("starts at 0");
  for (const concept of educationContent.addition.concepts) {
    await expect(learn.locator(`[data-concept="addition/${concept.id}"]`)).toContainText(concept.explanation.en);
  }
  await page.screenshot({path:info.outputPath("addition-learn.png"),animations:"disabled"});
  await page.getByRole("tab",{name:"Learn",exact:true}).focus();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("tab",{name:"Explore code",exact:true})).toBeFocused();
  const explore=page.locator("[data-addition-explore]");
  await expect(explore.getByRole("heading",{name:"Now change the program yourself"})).toBeVisible();
  // The step-by-step walkthrough lives only on Learn; Explore is hands-on.
  await expect(explore.locator(".syntax-lab")).toHaveCount(0);
  const experiment=explore.locator(".add-exp");
  await expect(experiment).toContainText("Experiment 1 of 4");
  await expect(experiment.getByRole("button",{name:"Previous",exact:true})).toBeDisabled();
  // The seeded draft is "WRITE 42.", so the number experiments have no line to change.
  await expect(experiment).toContainText("no longer has the line");
  for (let i=0;i<3;i++) await experiment.getByRole("button",{name:"Next experiment",exact:true}).click();
  await expect(experiment).toContainText("Experiment 4 of 4");
  await experiment.getByRole("button",{name:"Show answer",exact:true}).click();
  await expect(experiment.locator(".add-exp-result")).toHaveText("Screen before: 42 → after: an error");
  await explore.getByRole("button",{name:ui.en.run,exact:true}).click();
  await expect(explore.getByTestId("output")).toContainText("42");
  await page.screenshot({path:info.outputPath("addition-explore.png"),animations:"disabled"});
  const progress=await page.evaluate(()=>JSON.parse(localStorage.getItem("abap2-master-progress")!));
  expect(progress.missions).toEqual([]);expect(progress.labs).toEqual([]);expect(progress.passedChallenges).toEqual([]);
  await page.reload();
  await expect(page.locator(".lesson-header-objectives ul")).toBeVisible();
  expect(await page.evaluate(()=>localStorage.getItem("abap2-workspace:addition:visualize"))).toBe("WRITE 42.");
  // Experiments follow the learner's own numbers, not the original 5 and 8.
  await tab(page,"en","visualize");
  await edit(page,additionExample.replace("VALUE 5","VALUE 3").replace("VALUE 8","VALUE 5"));
  const ownExperiment=page.locator("[data-addition-explore] .add-exp");
  await expect(ownExperiment.locator("pre").first()).toHaveText("DATA lv_first TYPE i VALUE 3.");
  await ownExperiment.getByRole("button",{name:"Show answer",exact:true}).click();
  await expect(ownExperiment).toContainText("lv_result = lv_first + lv_second = 100 + 5 = 105");
  await expect(ownExperiment.locator(".add-exp-result")).toHaveText("Screen before: 8 → after: 105");
  await ownExperiment.getByRole("button",{name:"Next experiment",exact:true}).click();
  await ownExperiment.getByRole("button",{name:"Show answer",exact:true}).click();
  await expect(ownExperiment.locator(".add-exp-result")).toHaveText("Screen before: 8 → after: 5");
  await tab(page,"en","challenge");
  const brief=page.locator("[data-addition-challenge]");
  await expect(brief.getByRole("heading",{level:2})).toContainText("10 boxes and 20 boxes");
  await brief.getByText("Stuck? Open one hint at a time").click();
  await brief.getByText("Hint 2",{exact:true}).click();
  await expect(brief).toContainText("VALUE 20");
  await brief.getByRole("button",{name:"Experiment on Explore code"}).click();
  await expect(page.getByRole("tab",{name:"Explore code",exact:true})).toHaveAttribute("aria-selected","true");
  await tab(page,"en","challenge");
  await expect(page.getByRole("button",{name:ui.en.complete,exact:true})).toBeDisabled();
  await openLesson(page,"structures");
  await expect(page.getByRole("tab",{name:"Explore code",exact:true})).toBeVisible();
  await expect(page.getByRole("heading",{name:"What you’ll learn"})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
